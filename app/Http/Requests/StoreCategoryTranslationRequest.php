<?php

namespace App\Http\Requests;

use Illuminate\Foundation\Http\FormRequest;
use Illuminate\Validation\Rule;

class StoreCategoryTranslationRequest extends FormRequest
{
    /**
     * اجازه دسترسی به Request
     */
    public function authorize(): bool
    {
        return true;
    }

    /**
     * قوانین اعتبارسنجی
     */
    public function rules(): array
    {
        return [

            /*
            |--------------------------------------------------------------------------
            | دسته‌بندی
            |--------------------------------------------------------------------------
            */
            'category_id' => [
                'bail',
                'required',
                'integer',
                'min:1',
                'exists:categories,id',
            ],

            /*
            |--------------------------------------------------------------------------
            | زبان
            |--------------------------------------------------------------------------
            */
            'locale' => [
                'bail',
                'required',
                'string',
                'size:2',
                Rule::in([
                    'fa',
                    'en',
                    'ar',
                ]),

                // هر دسته فقط یک ترجمه برای هر زبان
                Rule::unique('category_translations', 'locale')
                    ->where(function ($query) {
                        return $query->where(
                            'category_id',
                            $this->input('category_id')
                        );
                    }),
            ],

            /*
            |--------------------------------------------------------------------------
            | نام
            |--------------------------------------------------------------------------
            */
            'name' => [
                'bail',
                'required',
                'string',
                'min:2',
                'max:255',
            ],

            /*
            |--------------------------------------------------------------------------
            | Slug
            |--------------------------------------------------------------------------
            */
            'slug' => [
                'bail',
                'required',
                'string',
                'min:2',
                'max:255',

                /*
                 * فقط:
                 * a-z
                 * اعداد
                 * -
                 */
                'regex:/^[a-z0-9]+(?:-[a-z0-9]+)*$/',

                // Slug در هر زبان باید یکتا باشد
                Rule::unique('category_translations', 'slug')
                    ->where(function ($query) {
                        return $query->where(
                            'locale',
                            $this->input('locale')
                        );
                    }),
            ],

            /*
            |--------------------------------------------------------------------------
            | توضیح کوتاه
            |--------------------------------------------------------------------------
            */
            'short_description' => [
                'nullable',
                'string',
                'max:500',
            ],

            /*
            |--------------------------------------------------------------------------
            | توضیحات کامل
            |--------------------------------------------------------------------------
            */
            'description' => [
                'nullable',
                'string',
            ],

            /*
            |--------------------------------------------------------------------------
            | SEO Title
            |--------------------------------------------------------------------------
            */
            'meta_title' => [
                'nullable',
                'string',
                'max:60',
            ],

            /*
            |--------------------------------------------------------------------------
            | SEO Description
            |--------------------------------------------------------------------------
            */
            'meta_description' => [
                'nullable',
                'string',
                'max:160',
            ],

            /*
            |--------------------------------------------------------------------------
            | SEO Keywords
            |--------------------------------------------------------------------------
            */
            'meta_keywords' => [
                'nullable',
                'string',
                'max:500',
            ],
        ];
    }

