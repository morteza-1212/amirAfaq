<?php

namespace App\Support;

use Illuminate\Support\Str;

class PersianSlugger
{
    /**
     * نقشه تبدیل حروف فارسی/عربی به معادل لاتین
     */
    protected static array $map = [
        'آ' => 'a',  'ا' => 'a',  'ب' => 'b',  'پ' => 'p',
        'ت' => 't',  'ث' => 's',  'ج' => 'j',  'چ' => 'ch',
        'ح' => 'h',  'خ' => 'kh', 'د' => 'd',  'ذ' => 'z',
        'ر' => 'r',  'ز' => 'z',  'ژ' => 'zh', 'س' => 's',
        'ش' => 'sh', 'ص' => 's',  'ض' => 'z',  'ط' => 't',
        'ظ' => 'z',  'ع' => 'a',  'غ' => 'gh', 'ف' => 'f',
        'ق' => 'gh', 'ک' => 'k',  'ك' => 'k',  'گ' => 'g',
        'ل' => 'l',  'م' => 'm',  'ن' => 'n',  'و' => 'v',
        'ه' => 'h',  'ی' => 'y',  'ي' => 'y',  'ء' => '',
        'ئ' => 'y',  'أ' => 'a',  'إ' => 'e',  'ؤ' => 'o',
        'ة' => 'h',  'ى' => 'a',

        // اعداد فارسی/عربی
        '۰' => '0', '۱' => '1', '۲' => '2', '۳' => '3', '۴' => '4',
        '۵' => '5', '۶' => '6', '۷' => '7', '۸' => '8', '۹' => '9',
        '٠' => '0', '١' => '1', '٢' => '2', '٣' => '3', '٤' => '4',
        '٥' => '5', '٦' => '6', '٧' => '7', '٨' => '8', '٩' => '9',

        // علائم رایج
        '‌' => '-',  // نیم‌فاصله
        ' ' => '-',
        '&' => 'and',
    ];

    /**
     * تولید اسلاگ از یک رشته (فارسی یا انگلیسی)
     */
    public static function make(string $value, string $fallback = 'category'): string
    {
        $value = trim($value);

        if ($value === '') {
            return $fallback;
        }

        // 1) تبدیل حروف فارسی/عربی به لاتین
        $transliterated = strtr($value, static::$map);

        // 2) حذف کاراکترهای غیرمجاز (فقط حروف، اعداد، فاصله، خط تیره، آندرلاین)
        $transliterated = preg_replace('/[^\p{L}\p{N}\s\-_]/u', '', $transliterated);

        // 3) اسلاگ استاندارد لاراول
        $slug = Str::slug($transliterated, '-');

        // 4) اگر خالی شد → fallback
        return $slug !== '' ? $slug : $fallback;
    }
}
